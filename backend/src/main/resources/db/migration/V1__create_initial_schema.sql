CREATE TABLE departments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_departments_name UNIQUE (department_name)
);

CREATE TABLE roles (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    CONSTRAINT uk_roles_name UNIQUE (role_name)
);

CREATE TABLE employees (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    manager_id BIGINT,
    employee_number VARCHAR(50) NOT NULL,
    full_name VARCHAR(200) NOT NULL,
    email VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    job_title VARCHAR(150),
    hire_date DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_employees_number UNIQUE (employee_number),
    CONSTRAINT uk_employees_email UNIQUE (email),
    CONSTRAINT fk_employees_department FOREIGN KEY (department_id)
        REFERENCES departments (department_id),
    CONSTRAINT fk_employees_manager FOREIGN KEY (manager_id)
        REFERENCES employees (employee_id),
    CONSTRAINT ck_employees_not_self_managed CHECK (manager_id IS NULL OR manager_id <> employee_id)
);

CREATE TABLE employee_roles (
    employee_role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT uk_employee_roles_assignment UNIQUE (employee_id, role_id),
    CONSTRAINT fk_employee_roles_employee FOREIGN KEY (employee_id)
        REFERENCES employees (employee_id) ON DELETE CASCADE,
    CONSTRAINT fk_employee_roles_role FOREIGN KEY (role_id)
        REFERENCES roles (role_id) ON DELETE CASCADE
);

CREATE TABLE leave_types (
    leave_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leave_name VARCHAR(100) NOT NULL,
    description TEXT,
    requires_approval BOOLEAN NOT NULL DEFAULT TRUE,
    is_paid BOOLEAN NOT NULL DEFAULT TRUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_leave_types_name UNIQUE (leave_name)
);

CREATE TABLE leave_balances (
    balance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    leave_type_id BIGINT NOT NULL,
    leave_year INTEGER NOT NULL,
    entitled_days NUMERIC(8, 2) NOT NULL DEFAULT 0,
    used_days NUMERIC(8, 2) NOT NULL DEFAULT 0,
    carried_forward_days NUMERIC(8, 2) NOT NULL DEFAULT 0,
    CONSTRAINT uk_leave_balances_employee_type_year UNIQUE (employee_id, leave_type_id, leave_year),
    CONSTRAINT ck_leave_balances_year CHECK (leave_year BETWEEN 1900 AND 9999),
    CONSTRAINT ck_leave_balances_nonnegative CHECK (
        entitled_days >= 0 AND used_days >= 0 AND carried_forward_days >= 0
    ),
    CONSTRAINT fk_leave_balances_employee FOREIGN KEY (employee_id)
        REFERENCES employees (employee_id) ON DELETE CASCADE,
    CONSTRAINT fk_leave_balances_type FOREIGN KEY (leave_type_id)
        REFERENCES leave_types (leave_type_id)
);

CREATE TABLE leave_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    leave_type_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    total_days NUMERIC(8, 2) NOT NULL,
    reason TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_leave_requests_date_range CHECK (end_date >= start_date),
    CONSTRAINT ck_leave_requests_total_days CHECK (total_days > 0),
    CONSTRAINT ck_leave_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT fk_leave_requests_employee FOREIGN KEY (employee_id)
        REFERENCES employees (employee_id),
    CONSTRAINT fk_leave_requests_type FOREIGN KEY (leave_type_id)
        REFERENCES leave_types (leave_type_id)
);

CREATE TABLE approvals (
    approval_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL,
    approver_id BIGINT NOT NULL,
    approval_level INTEGER NOT NULL,
    decision VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    comments TEXT,
    decided_at TIMESTAMP,
    CONSTRAINT uk_approvals_request_level UNIQUE (request_id, approval_level),
    CONSTRAINT ck_approvals_level CHECK (approval_level > 0),
    CONSTRAINT ck_approvals_decision CHECK (decision IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT fk_approvals_request FOREIGN KEY (request_id)
        REFERENCES leave_requests (request_id) ON DELETE CASCADE,
    CONSTRAINT fk_approvals_approver FOREIGN KEY (approver_id)
        REFERENCES employees (employee_id)
);

CREATE TABLE audit_logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100) NOT NULL,
    entity_id BIGINT,
    details TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_logs_employee FOREIGN KEY (employee_id)
        REFERENCES employees (employee_id) ON DELETE SET NULL
);

CREATE INDEX idx_employees_department ON employees (department_id);
CREATE INDEX idx_employees_manager ON employees (manager_id);
CREATE INDEX idx_employee_roles_role ON employee_roles (role_id);
CREATE INDEX idx_leave_balances_employee ON leave_balances (employee_id);
CREATE INDEX idx_leave_requests_employee ON leave_requests (employee_id);
CREATE INDEX idx_leave_requests_status ON leave_requests (status);
CREATE INDEX idx_leave_requests_dates ON leave_requests (start_date, end_date);
CREATE INDEX idx_approvals_approver ON approvals (approver_id);
CREATE INDEX idx_audit_logs_entity ON audit_logs (entity_type, entity_id);
CREATE INDEX idx_audit_logs_created_at ON audit_logs (created_at);
